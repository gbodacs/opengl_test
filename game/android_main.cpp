// Android entry point (android.app.NativeActivity + android_native_app_glue).
// Responsible for: EGL window lifecycle, pumping the event loop, forwarding
// touch/back-button input, and extracting bundled assets to internal storage
// on first launch so the existing relative-path ("data/...") file loaders
// keep working unmodified.
#include <android_native_app_glue.h>
#include <android/log.h>
#include <android/asset_manager.h>
#include <sys/stat.h>
#include <unistd.h>
#include <cstdio>
#include <string>

#include "game.h"

#define LOG_TAG "opengl_test"
#define LOGI(...) ((void)__android_log_print(ANDROID_LOG_INFO, LOG_TAG, __VA_ARGS__))
#define LOGE(...) ((void)__android_log_print(ANDROID_LOG_ERROR, LOG_TAG, __VA_ARGS__))

namespace
{
    void MakeDirs(const std::string& path)
    {
        std::string current;
        for (char c : path)
        {
            current += c;
            if (c == '/')
            {
                mkdir(current.c_str(), 0771);
            }
        }
        mkdir(path.c_str(), 0771);
    }

    void CopyAsset(AAssetManager* mgr, const std::string& relativePath, const std::string& destRoot)
    {
        AAsset* asset = AAssetManager_open(mgr, relativePath.c_str(), AASSET_MODE_BUFFER);
        if (asset == nullptr)
        {
            LOGE("Failed to open asset: %s", relativePath.c_str());
            return;
        }

        const std::string destPath = destRoot + "/" + relativePath;
        const size_t lastSlash = destPath.find_last_of('/');
        if (lastSlash != std::string::npos)
        {
            MakeDirs(destPath.substr(0, lastSlash));
        }

        const off_t length = AAsset_getLength(asset);
        const void* data = AAsset_getBuffer(asset);
        FILE* out = fopen(destPath.c_str(), "wb");
        if (out != nullptr)
        {
            if (data != nullptr && length > 0)
            {
                fwrite(data, 1, static_cast<size_t>(length), out);
            }
            fclose(out);
        }
        AAsset_close(asset);
    }

    // Reads assets_manifest.txt (generated by app/build.gradle from the repo's
    // data/ folder) and copies every listed file into destRoot, preserving
    // its relative path/subdirectories.
    void ExtractAssets(AAssetManager* mgr, const std::string& destRoot)
    {
        AAsset* manifest = AAssetManager_open(mgr, "assets_manifest.txt", AASSET_MODE_BUFFER);
        if (manifest == nullptr)
        {
            LOGE("assets_manifest.txt missing from APK assets - rebuild with Gradle");
            return;
        }

        const off_t length = AAsset_getLength(manifest);
        std::string contents(static_cast<size_t>(length), '\0');
        AAsset_read(manifest, contents.data(), contents.size());
        AAsset_close(manifest);

        std::string line;
        for (char c : contents)
        {
            if (c == '\n' || c == '\r')
            {
                if (!line.empty())
                {
                    CopyAsset(mgr, line, destRoot);
                }
                line.clear();
            }
            else
            {
                line += c;
            }
        }
        if (!line.empty())
        {
            CopyAsset(mgr, line, destRoot);
        }
    }
}

struct AppState
{
    cGame game;
    bool initialized = false;
    bool hasFocus = false;
};

static int32_t HandleInput(struct android_app* app, AInputEvent* event)
{
    AppState* state = static_cast<AppState*>(app->userData);
    if (state == nullptr || !state->initialized)
    {
        return 0;
    }

    if (AInputEvent_getType(event) == AINPUT_EVENT_TYPE_MOTION)
    {
        const int32_t action = AMotionEvent_getAction(event) & AMOTION_EVENT_ACTION_MASK;
        const float x = AMotionEvent_getX(event, 0);
        const float y = AMotionEvent_getY(event, 0);
        const bool down = (action == AMOTION_EVENT_ACTION_DOWN ||
                           action == AMOTION_EVENT_ACTION_MOVE ||
                           action == AMOTION_EVENT_ACTION_POINTER_DOWN);

        state->game.input->SetTouch(x, y, down);
        return 1;
    }

    if (AInputEvent_getType(event) == AINPUT_EVENT_TYPE_KEY)
    {
        if (AKeyEvent_getKeyCode(event) == AKEYCODE_BACK)
        {
            state->game.engine->RequestClose();
            return 1;
        }
    }

    return 0;
}

static void HandleCmd(struct android_app* app, int32_t cmd)
{
    AppState* state = static_cast<AppState*>(app->userData);

    switch (cmd)
    {
        case APP_CMD_INIT_WINDOW:
            if (app->window != nullptr)
            {
                if (!state->initialized)
                {
                    if (chdir(app->activity->internalDataPath) != 0)
                    {
                        LOGE("chdir to internal data path failed: %s", app->activity->internalDataPath);
                    }
                    ExtractAssets(app->activity->assetManager, app->activity->internalDataPath);

                    state->game.engine = new Engine();
                    if (!state->game.engine->InitAndroid(app->window))
                    {
                        LOGE("Engine::InitAndroid failed");
                        break;
                    }
                    if (state->game.Init())
                    {
                        state->initialized = true;
                    }
                    else
                    {
                        LOGE("cGame::Init failed");
                    }
                }
                else
                {
                    state->game.engine->InitAndroid(app->window);
                }
            }
            break;

        case APP_CMD_TERM_WINDOW:
            if (state->initialized)
            {
                state->game.engine->DestroySurface();
            }
            break;

        case APP_CMD_GAINED_FOCUS:
            state->hasFocus = true;
            break;

        case APP_CMD_LOST_FOCUS:
            state->hasFocus = false;
            break;

        case APP_CMD_DESTROY:
            if (state->initialized)
            {
                state->game.Done();
                state->initialized = false;
            }
            break;

        default:
            break;
    }
}

void android_main(struct android_app* app)
{
    AppState state;
    app->userData = &state;
    app->onAppCmd = HandleCmd;
    app->onInputEvent = HandleInput;

    while (!app->destroyRequested)
    {
        int events = 0;
        struct android_poll_source* source = nullptr;

        // Block for events until the window is ready; once running, poll
        // without blocking so we can keep rendering frames.
        while (ALooper_pollAll(state.initialized ? 0 : -1, nullptr, &events, reinterpret_cast<void**>(&source)) >= 0)
        {
            if (source != nullptr)
            {
                source->process(app, source);
            }
            if (app->destroyRequested)
            {
                break;
            }
        }

        if (state.initialized && state.hasFocus)
        {
            state.game.Step();
            if (state.game.engine->ShouldClose())
            {
                ANativeActivity_finish(app->activity);
            }
        }
    }
}
